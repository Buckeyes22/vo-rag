def _image_element(index: int) -> ParsedElement:
    return ParsedElement(
        element_id=f"img-{index}",
        element_type=ElementType.IMAGE,
        text="",
        page_number=index + 1,
    )


def _text_element(index: int, chars: int) -> ParsedElement:
    return ParsedElement(
        element_id=f"txt-{index}",
        element_type=ElementType.NARRATIVE_TEXT,
        text="x" * chars,
        page_number=index + 1,
    )


def _tiny_png(color: tuple[int, int, int] = (10, 20, 30)) -> bytes:
    pil_image = pytest.importorskip("PIL.Image")
    import io

    image = pil_image.new("RGB", (4, 4), color=color)
    buf = io.BytesIO()
    image.save(buf, format="PNG")
    return buf.getvalue()


def _pdf_page_count(path: str) -> int:
    doc = fitz.open(path)
    try:
        return int(doc.page_count)
    finally:
        doc.close()


