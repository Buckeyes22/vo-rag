def test_write_pdf_from_images_composites_transparent_webp_onto_white(
    tmp_path: Path,
) -> None:
    """End-to-end: an RGBA WEBP page with black
    text on a fully transparent background renders with a white background,
    not black -- through the full _write_pdf_from_images pipeline."""
    pil_image = pytest.importorskip("PIL.Image")
    import io

    image = pil_image.new("RGBA", (8, 8), (0, 0, 0, 0))
    for x in range(2):  # a solid opaque black "text" block, top-left
        for y in range(2):
            image.putpixel((x, y), (0, 0, 0, 255))
    buf = io.BytesIO()
    image.save(buf, format="WEBP", lossless=True)
    webp_bytes = buf.getvalue()
    pdf_path = tmp_path / "transparent.pdf"

    _write_pdf_from_images([(webp_bytes, "webp")], pdf_path)

    doc = fitz.open(str(pdf_path))
    try:
        pix = doc[0].get_pixmap(dpi=72)
        bg_pixel = pix.pixel(int(pix.width * 0.85), int(pix.height * 0.85))
        text_pixel = pix.pixel(int(pix.width * 0.1), int(pix.height * 0.1))
        assert bg_pixel[:3] == (255, 255, 255)  # transparent region -> white
        assert text_pixel[:3] != (255, 255, 255)  # opaque black text stays dark
    finally:
        doc.close()


