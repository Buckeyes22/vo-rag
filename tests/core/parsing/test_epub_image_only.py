def test_write_pdf_from_images_builds_a_page_per_image_losslessly(tmp_path: Path) -> None:
    """pymupdf-based synthesis, one page per image,
    counted with pymupdf instead of pypdfium2."""
    payloads = [_tiny_png(c) for c in [(1, 2, 3), (4, 5, 6), (7, 8, 9)]]
    images: list[tuple[bytes, str]] = [(payload, "png") for payload in payloads]
    pdf_path = tmp_path / "out.pdf"

    _write_pdf_from_images(images, pdf_path)

    doc = fitz.open(str(pdf_path))
    try:
        assert doc.page_count == 3
        for page in doc:
            assert len(page.get_images(full=True)) >= 1
    finally:
        doc.close()


