"""Image-only EPUBs (page scans) get OCR'd through docling, not the normal
text path (VOR-1427).

``is_image_only``, the router's ``_parse_ebook`` restore/cleanup logic, and
the spine-image / PDF-synthesis helpers all have no-extra-deps coverage
(fake ``book`` / fake ``epub`` parser / fake ``docling``, plus Pillow and
pymupdf -- both guaranteed in the locked CI env, see the module docstrings
on ``_write_pdf_from_images`` and the base ``pymupdf`` dependency). The
real ``ebooklib``/``pypandoc``/``pypdfium2`` stack is absent from the locked CI
env, so the path is covered through fakes rather than that stack.

The full ebooklib-based end-to-end tests are guarded by
``pytest.importorskip`` since ``ebooklib``/``pypandoc`` are ``runtime``-extra
only. They count PDF pages with pymupdf, not pypdfium2, because pypdfium2
isn't in the locked CI env and pymupdf is.
"""

