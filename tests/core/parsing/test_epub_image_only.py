@pytest.mark.asyncio
async def test_epub_with_text_and_a_few_images_uses_normal_path(figures: FigureStore) -> None:
    ebooklib = pytest.importorskip("ebooklib")
    epub_mod = pytest.importorskip("ebooklib.epub")
    pytest.importorskip("pypandoc")
    _ = ebooklib

    from vo_rag.core.parsing.parsers.epub import EpubParser

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "text_book.epub"
        book = epub_mod.EpubBook()
        book.set_identifier("vorag-test-text-epub")
        book.set_title("A Real Book")
        book.set_language("en")
        book.add_author("Some Author")

        chapters = []
        for i in range(3):
            chapter = epub_mod.EpubHtml(
                title=f"Chapter {i + 1}", file_name=f"chap_{i}.xhtml", lang="en"
            )
            paragraph = "This chapter has real narrative prose. " * 20
            img = ""
            if i == 0:
                img_item = epub_mod.EpubItem(
                    uid="img0",
                    file_name="images/cover.png",
                    media_type="image/png",
                    content=_tiny_png(),
                )
                book.add_item(img_item)
                img = '<img src="images/cover.png" alt="cover"/>'
            chapter.content = f"<html><body>{img}<p>{paragraph}</p></body></html>"
            book.add_item(chapter)
            chapters.append(chapter)

        book.toc = tuple(chapters)
        book.add_item(epub_mod.EpubNcx())
        book.add_item(epub_mod.EpubNav())
        book.spine = ["nav", *chapters]
        epub_mod.write_epub(str(path), book)

        parser = EpubParser(figures)
        doc = await parser.parse(str(path))

    assert doc.parser_used == "epub"
    assert doc.title == "A Real Book"
    assert any(element.text.strip() for element in doc.elements)
