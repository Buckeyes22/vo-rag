def test_flatten_to_opaque_composites_transparency_onto_white() -> None:
    """Transparent regions must come out white, not
    black. ``Image.convert("RGB")`` alone drops alpha but keeps whatever RGB
    sits *under* a transparent pixel -- often ``(0, 0, 0)`` -- so black text
    on a transparent background would otherwise turn black-on-black."""
    pil_image = pytest.importorskip("PIL.Image")

    rgba = pil_image.new("RGBA", (4, 4), (0, 0, 0, 0))  # fully transparent
    rgba.putpixel((0, 0), (0, 0, 0, 255))  # opaque black "text" pixel

    flattened = _flatten_to_opaque(rgba)

    assert flattened.mode == "RGB"
    assert flattened.getpixel((0, 0)) == (0, 0, 0)  # text stays black
    assert flattened.getpixel((1, 1)) == (255, 255, 255)  # transparent bg -> white


def test_flatten_to_opaque_handles_palette_transparency() -> None:
    pil_image = pytest.importorskip("PIL.Image")

