class _FakeEpubItem:
    def __init__(self, item_id: str, file_name: str, media_type: str, content: bytes) -> None:
        self.id = item_id
        self.file_name = file_name
        self.media_type = media_type
        self._content = content

    def get_content(self) -> bytes:
        return self._content


class _FakeEpubBook:
    """Minimal stand-in for ``ebooklib.epub.EpubBook`` -- just the spine /
    id / href lookups ``_spine_ordered_image_bytes`` actually uses."""

    def __init__(self) -> None:
        self._by_id: dict[str, _FakeEpubItem] = {}
        self._by_href: dict[str, _FakeEpubItem] = {}
        self.spine: list[tuple[str, str]] = []

    def add(self, item: _FakeEpubItem) -> _FakeEpubItem:
        self._by_id[item.id] = item
        self._by_href[item.file_name] = item
        return item

    def get_item_with_id(self, idref: str) -> _FakeEpubItem | None:
        return self._by_id.get(idref)

    def get_item_with_href(self, href: str) -> _FakeEpubItem | None:
        return self._by_href.get(href)


def _add_page(book: _FakeEpubBook, page_id: str, file_name: str, html: bytes) -> None:
    book.add(_FakeEpubItem(page_id, file_name, "application/xhtml+xml", html))
    book.spine.append((page_id, "yes"))


def test_spine_ordered_image_bytes_reads_img_src_in_spine_order() -> None:
    book = _FakeEpubBook()
    payloads = [_tiny_png(c) for c in [(10, 20, 30), (200, 100, 50), (0, 255, 0)]]
    for i, payload in enumerate(payloads):
        book.add(_FakeEpubItem(f"img{i}", f"images/p{i}.png", "image/png", payload))
        html = f'<html><body><img src="images/p{i}.png"/></body></html>'.encode()
        _add_page(book, f"page{i}", f"page{i}.xhtml", html)

    result = _spine_ordered_image_bytes(book)

    assert [payload for payload, _ext in result] == payloads
    assert [ext for _payload, ext in result] == ["png", "png", "png"]


def test_spine_ordered_image_bytes_handles_svg_image_href_and_xlink_href() -> None:
    """<image href> and <image xlink:href> (SVG-
    wrapped page scans) must resolve alongside plain <img src>, in order."""
    book = _FakeEpubBook()
    png_a, png_b, png_c = (_tiny_png(c) for c in [(1, 2, 3), (4, 5, 6), (7, 8, 9)])

    book.add(_FakeEpubItem("imgA", "images/a.png", "image/png", png_a))
    _add_page(book, "pageA", "pageA.xhtml", b'<html><body><img src="images/a.png"/></body></html>')

    book.add(_FakeEpubItem("imgB", "images/b.png", "image/png", png_b))
    _add_page(
        book,
        "pageB",
        "pageB.xhtml",
        b'<html><body><svg><image xlink:href="images/b.png"/></svg></body></html>',
    )

    book.add(_FakeEpubItem("imgC", "images/c.png", "image/png", png_c))
    _add_page(
        book,
        "pageC",
        "pageC.xhtml",
        b'<html><body><svg><image href="images/c.png"/></svg></body></html>',
    )

    result = _spine_ordered_image_bytes(book)

    assert [payload for payload, _ext in result] == [png_a, png_b, png_c]


def test_spine_ordered_image_bytes_ignores_data_src_attribute() -> None:
    """A "data-src=" must not be mistaken for "src=";
    a page with only a lazy-load data-src yields no images."""
    book = _FakeEpubBook()
    decoy = _tiny_png((9, 9, 9))
    book.add(_FakeEpubItem("decoy", "images/decoy.png", "image/png", decoy))
    _add_page(
        book,
        "page0",
        "page0.xhtml",
        b'<html><body><img data-src="images/decoy.png" alt="lazy"/></body></html>',
    )

    assert _spine_ordered_image_bytes(book) == []


def test_spine_ordered_image_bytes_mixed_data_src_and_real_src_on_same_page() -> None:
    book = _FakeEpubBook()
    decoy = _tiny_png((1, 1, 1))
    real = _tiny_png((2, 2, 2))
    book.add(_FakeEpubItem("decoy", "images/decoy.png", "image/png", decoy))
    book.add(_FakeEpubItem("real", "images/real.png", "image/png", real))
    html = (
        b"<html><body>"
        b'<img data-src="images/decoy.png" alt="lazy"/>'
        b'<img src="images/real.png"/>'
        b"</body></html>"
    )
    _add_page(book, "page0", "page0.xhtml", html)

    result = _spine_ordered_image_bytes(book)

    assert [payload for payload, _ext in result] == [real]


def test_spine_ordered_image_bytes_ignores_src_inside_another_attribute_value() -> None:
    """A "src=" sitting inside an unrelated attribute's
    *value* (here alt="x src=fake") must not be mistaken for a real src
    attribute -- only a real HTML/XML parser (not a regex) can tell those
    apart reliably."""
    book = _FakeEpubBook()
    decoy = _tiny_png((3, 3, 3))
    real = _tiny_png((4, 4, 4))
    book.add(_FakeEpubItem("fake", "images/fake.png", "image/png", decoy))
    book.add(_FakeEpubItem("real", "images/real.png", "image/png", real))
    html = b'<html><body><img alt="x src=fake" src="images/real.png"/></body></html>'
    _add_page(book, "page0", "page0.xhtml", html)

    result = _spine_ordered_image_bytes(book)

    assert [payload for payload, _ext in result] == [real]


