"""Deterministic id derivation for exported VCE records.

The export contract requires that re-running on the same video yields
identical ``id`` fields. The derivation is
:func:`vo_rag.pipelines.vce.types.record_id_for_interval` and must be
byte-stable across processes, Python versions, and host OS (per the
deterministic-id contract; see `vo_rag.core.idempotency`).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.pipelines.vce._contract import VceRowSchema
from vo_rag.pipelines.vce.baseline import load_baseline_rows
from vo_rag.pipelines.vce.types import VceExportEvidence, record_id_for_interval


class TestRecordIdDerivation:
    """The id derivation must be deterministic and the 95 baseline ids must survive."""

    def test_same_inputs_yield_same_id(self) -> None:
        first = record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0, length=26)
        second = record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0, length=26)
        assert first == second
        assert len(first) == 26
        assert first == first.upper()  # uppercase hex

    def test_different_intervals_yield_different_ids(self) -> None:
        id_a = record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0)
        id_b = record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=21.0)
        assert id_a != id_b

    def test_different_videos_yield_different_ids(self) -> None:
        id_a = record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0)
        id_b = record_id_for_interval(video_id="yt:xyz", start_ts=10.0, end_ts=20.0)
        assert id_a != id_b

    def test_length_validation(self) -> None:
        with pytest.raises(ValueError):
            record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0, length=0)
        with pytest.raises(ValueError):
            record_id_for_interval(video_id="yt:abc", start_ts=10.0, end_ts=20.0, length=65)

    def test_rounding_to_millisecond_precision(self) -> None:
        """Float drift in the baseline's string fields must not change the id."""
        id_a = record_id_for_interval(video_id="yt:abc", start_ts=10.0001, end_ts=20.0001)
        id_b = record_id_for_interval(video_id="yt:abc", start_ts=10.0002, end_ts=20.0002)
        # Both round to "10.000"/"20.000" at 3 decimals — must produce same id.
        assert id_a == id_b


class TestBaselinePreservation:
    """The export must reproduce the 95 baseline ids for unchanged intervals.

    The legacy baseline ids (``DDDDDDDDDDDDDDDDDDDDDDDD`` and friends) were
    generated by an unknown legacy formula. The pipeline does **not** reverse
    engineer that formula — instead the structured_extract stage looks up
    the baseline row by ``(video_id, start, end)`` and reuses the legacy id
    verbatim. This preserves downstream consumer's ``case_id = vce:<id>`` mapping
    across re-runs without depending on a formula we don't have.
    """

    def test_baseline_loader_preserves_legacy_ids(self, baseline_rows_path: Path) -> None:
        """The loader indexes by interval and the legacy_id is what we ship back."""
        index = load_baseline_rows(baseline_rows_path)
        for row in index.rows:
            key = (
                row["video_id"],
                round(float(row["start_ts"]), 3),
                round(float(row["end_ts"]), 3),
            )
            looked_up = index.by_interval.get(key)
            assert looked_up is not None
            assert looked_up["legacy_id"] == row["legacy_id"]

    def test_baseline_loader_handles_string_ts(self, baseline_rows_path: Path) -> None:
        """Legacy rows.json has string start_ts/end_ts — loader must coerce."""
        index = load_baseline_rows(baseline_rows_path)
        for row in index.rows:
            assert isinstance(row["start_ts"], float)
            assert isinstance(row["end_ts"], float)

    def test_baseline_index_lookup_by_interval(self, baseline_rows_path: Path) -> None:
        index = load_baseline_rows(baseline_rows_path)
        row = index.by_interval.get(("yt:abc", 10.0, 20.0))
        assert row is not None
        assert row["legacy_id"] == "BBBBBBBBBBBBBBBBBBBBBBBB"

    def test_baseline_loader_missing_file_raises(self, tmp_path: Path) -> None:
        from vo_rag.pipelines.vce.baseline import load_baseline_rows

        with pytest.raises(FileNotFoundError):
            load_baseline_rows(tmp_path / "does-not-exist.json")


class TestContractRoundTrip:
    """The Python mirror of vceRowSchema v2 must parse what VceExportRow produces."""

    def test_row_dict_parses_under_contract(self) -> None:
        from vo_rag.pipelines.vce.types import VceExportRow

        row = VceExportRow(
            id="DDDDDDDDDDDDDDDDDDDDDDDD",  # pragma: allowlist secret
            video_id="yt:abc",
            start_ts=10.0,
            end_ts=20.0,
            observation="test",
            evidence=VceExportEvidence.EXPLICIT_NUMERIC,
            transcript_excerpt="see how late he turns in here",
            transcript_source="whisperx",
            anchors=[],
        )
        dumped = row.model_dump(mode="json")
        # The contract mirror re-validates what the production model produced.
        VceRowSchema.model_validate(dumped)

    def test_row_with_anchor_parses_under_contract(self) -> None:
        from vo_rag.pipelines.vce.types import VceExportRow, VceRowAnchor

        row = VceExportRow(
            id="AAAAAAAAAAAAAAAAAAAAAAAA",
            video_id="yt:abc",
            start_ts=10.0,
            end_ts=20.0,
            observation="x",
            evidence=VceExportEvidence.INFERRED_FROM_AUDIO,
            transcript_excerpt="see this",
            transcript_source="whisperx",
            anchors=[
                VceRowAnchor(
                    frame_ts_seconds=15.0,
                    vlm_description="telemetry overlay visible",
                    region=None,
                    frame_path=None,
                )
            ],
        )
        dumped = row.model_dump(mode="json")
        VceRowSchema.model_validate(dumped)

    def test_contract_rejects_unknown_evidence_value(self) -> None:
        from pydantic import ValidationError

        with pytest.raises(ValidationError):
            VceRowSchema.model_validate(
                {
                    "id": "AAAAAAAAAAAAAAAAAAAAAAAA",
                    "video_id": "yt:abc",
                    "start_ts": 10.0,
                    "end_ts": 20.0,
                    "observation": "x",
                    "evidence": "made_up_evidence_kind",
                    "transcript_excerpt": "",
                    "transcript_source": None,
                    "anchors": [],
                }
            )
